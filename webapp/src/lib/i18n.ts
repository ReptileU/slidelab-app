export const DICTS: Record<Lang, Dict> = { ru, uz, en };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let text = DICTS[lang][key] ?? ru[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

export function guessLang(code?: string): Lang {
  if (code === "uz") return "uz";
  if (code && !["ru", "uk", "be", "kk"].some((p) => code.startsWith(p))) return "en";
  return "ru";
}

/** 29000 → «29 000» */
export function money(n: number): string {
  return n.toLocaleString("ru-RU").replace(/\s/g, " ");
}

export function formatDate(iso: string, lang: Lang): string {
  const locale = lang === "en" ? "en-GB" : lang === "uz" ? "uz-Latn-UZ" : "ru-RU";
  return new Date(iso).toLocaleDateString(locale, { day: "numeric", month: "long" });
}
